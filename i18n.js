  const LANGS = ["en", "he"];
  const DEFAULT_LANG = "en";

  let currentLang = DEFAULT_LANG;

  window.I18N = {
    DEFAULT_LANG,
    get lang() {
      return currentLang;
    },
    isRtl() {
      return currentLang === "he";
    },
    t(key, params) {
      const d = DICT[currentLang] || DICT[DEFAULT_LANG];
      let value = d[key] != null ? d[key] : key;
      if (params && typeof value === "string") {
        value = value.replace(/\{(\w+)\}/g, (_, k) => params[k] != null ? params[k] : "{" + k + "}");
      }
      return value;
    },
    async load() {
      try {
        const st = await getSetting("uiLang");
        currentLang = st && st.value && LANGS.includes(st.value) ? st.value : DEFAULT_LANG;
      } catch (e) {
        currentLang = DEFAULT_LANG;
      }
      window.__currentLang = currentLang;
      return currentLang;
    },
    async set(lang) {
      currentLang = LANGS.includes(lang) ? lang : DEFAULT_LANG;
      try {
        await setSetting("uiLang", currentLang);
      } catch (e) {}
      window.__currentLang = currentLang;
      return currentLang;
    },
    apply() {
      document.querySelectorAll("[data-i18n]").forEach((el) => {
        el.textContent = this.t(el.getAttribute("data-i18n"));
      });
      document.querySelectorAll("[data-i18n-title]").forEach((el) => {
        el.title = this.t(el.getAttribute("data-i18n-title"));
        if (el.hasAttribute("aria-label")) el.setAttribute("aria-label", el.title);
      });
      document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
        el.setAttribute("placeholder", this.t(el.getAttribute("data-i18n-placeholder")));
      });
      document.querySelectorAll("[data-i18n-label]").forEach((el) => {
        el.setAttribute("aria-label", this.t(el.getAttribute("data-i18n-label")));
      });
      const root = document.documentElement;
      root.lang = currentLang;
      root.setAttribute("dir", this.isRtl() ? "rtl" : "ltr");
    },
  };
